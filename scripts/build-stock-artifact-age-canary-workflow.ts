#!/usr/bin/env bun
import { resolve } from "node:path";
import { formatGeneratedPaths } from "./_codegen-output.ts";
import { pinnedAction } from "./action-pins.ts";

export const renderStockArtifactAgeCanaryWorkflow =
  (): string => `# Generated by scripts/build-stock-artifact-age-canary-workflow.ts. Do not edit.
name: stock-artifact-age-canary
on:
  schedule:
    - cron: '41 6 * * 1'
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: stock-artifact-age-canary
  cancel-in-progress: false
jobs:
  report:
    if: github.ref == format('refs/heads/{0}', github.event.repository.default_branch) && (github.event_name == 'schedule' || github.event_name == 'workflow_dispatch')
    runs-on: ubuntu-24.04
    timeout-minutes: 20
    permissions:
      contents: read
    steps:
      - uses: ${pinnedAction("actions/checkout")}
        with:
          persist-credentials: false
      - uses: ${pinnedAction("oven-sh/setup-bun")}
        with:
          bun-version-file: .bun-version
      - run: bun install --frozen-lockfile --ignore-scripts
      - name: Generate stock service catalogs
        run: |
          bun run codegen:node-releases
          bun run codegen:tomcat-catalog
      - name: Report stock service image ages
        run: bun run scripts/stock-artifact-age-canary.ts
`;

if (import.meta.main) {
  const output = resolve(import.meta.dirname, "../.github/workflows/stock-artifact-age-canary.yml");
  await Bun.write(output, renderStockArtifactAgeCanaryWorkflow());
  await formatGeneratedPaths([output, import.meta.path]);
}
