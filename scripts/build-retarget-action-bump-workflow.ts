#!/usr/bin/env bun
import { resolve } from "node:path";
import { formatGeneratedPaths } from "./_codegen-output.ts";
import { RUNTIME_BUNDLE_ACTION_PINS } from "./runtime-bundle-supply-chain.ts";

export const renderRetargetActionBumpWorkflow =
  (): string => `# Generated by scripts/build-retarget-action-bump-workflow.ts. Do not edit.
name: retarget-action-bump
on:
  pull_request_target:
    types: [opened, synchronize, reopened]
    paths:
      - .github/workflows/**
permissions:
  contents: read
concurrency:
  group: retarget-action-bump-\${{ github.event.pull_request.number }}
  cancel-in-progress: false
jobs:
  retarget:
    if: github.event.pull_request.user.login == 'dependabot[bot]' && github.event.pull_request.head.repo.full_name == github.repository
    runs-on: ubuntu-26.04
    timeout-minutes: 15
    permissions:
      contents: write
    steps:
      - uses: ${RUNTIME_BUNDLE_ACTION_PINS.checkout} # v7.0.1
        with:
          ref: \${{ github.event.pull_request.base.sha }}
          fetch-depth: 1
          persist-credentials: false
      - uses: ${RUNTIME_BUNDLE_ACTION_PINS.setupBun} # v2.0.2
        with:
          bun-version-file: .bun-version
      - run: bun install --frozen-lockfile
      - name: Retarget action pins onto the Dependabot branch
        env:
          GH_TOKEN: \${{ github.token }}
          BASE_SHA: \${{ github.event.pull_request.base.sha }}
          HEAD_SHA: \${{ github.event.pull_request.head.sha }}
          HEAD_REF: \${{ github.event.pull_request.head.ref }}
          PR_NUMBER: \${{ github.event.pull_request.number }}
        run: |
          set -euo pipefail
          case "$HEAD_REF" in
            ""|-*|*..*|*[!A-Za-z0-9._/-]*)
              printf 'refusing to push ref %s\\n' "$HEAD_REF" >&2
              exit 1
              ;;
          esac
          git config user.name "github-actions[bot]"
          git config user.email "github-actions[bot]@users.noreply.github.com"
          gh auth setup-git
          git fetch --no-tags origin "+refs/pull/\${PR_NUMBER}/head"
          git cat-file -e "$BASE_SHA^{commit}"
          git cat-file -e "$HEAD_SHA^{commit}"
          bun run scripts/retarget-action-bump.ts --base "$BASE_SHA" --head "$HEAD_SHA"
          if [ -z "$(git status --porcelain=v1)" ]; then
            exit 0
          fi
          worktree="$RUNNER_TEMP/retarget-action-bump"
          git worktree add --detach "$worktree" "$HEAD_SHA"
          while IFS= read -r -d '' path; do
            [ -n "$path" ] || continue
            mkdir -p "$worktree/$(dirname -- "$path")"
            cp -- "$path" "$worktree/$path"
          done < <(git diff --name-only -z HEAD)
          git -C "$worktree" add -A -- .github/workflows scripts core/test
          if git -C "$worktree" diff --cached --quiet; then
            exit 0
          fi
          if git -C "$worktree" diff --cached --name-only | grep -q '^\\.github/workflows/'; then
            printf 'refusing to push workflow edits with GITHUB_TOKEN\\n' >&2
            exit 1
          fi
          git -C "$worktree" commit -m "Retarget Dependabot action pins into the workflow generators"
          git -C "$worktree" push origin "HEAD:refs/heads/$HEAD_REF"
`;

if (import.meta.main) {
  const output = resolve(import.meta.dirname, "../.github/workflows/retarget-action-bump.yml");
  await Bun.write(output, renderRetargetActionBumpWorkflow());
  await formatGeneratedPaths([output, import.meta.path]);
}
