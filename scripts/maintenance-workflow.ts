import { RUNTIME_BUNDLE_ACTION_PINS } from "./runtime-bundle-supply-chain.ts";

type MaintenanceWorkflow = {
  readonly name: string;
  readonly cron: string;
  readonly branch: string;
  readonly ownedPaths: readonly [string, ...string[]];
  readonly proposal: {
    readonly name: string;
    readonly prepare: string;
    readonly checkAndReport: string;
  };
};

// The automation owns only the PR body text between these markers.
const REPORT_START = "<!-- maintenance-report:start -->";
const REPORT_END = "<!-- maintenance-report:end -->";
const shellQuote = (value: string): string => `'${value.replaceAll("'", "'\"'\"'")}'`;
const indentScript = (script: string): string =>
  script
    .trim()
    .split("\n")
    .map((line) => `          ${line}`)
    .join("\n");

// Trusted repository-authored hooks only. checkAndReport sets TITLE and BODY_FILE.
export const renderMaintenanceWorkflow = (policy: MaintenanceWorkflow): string => {
  const paths = policy.ownedPaths.map(shellQuote).join(" ");
  const failureTitle = `${policy.name} automation failure`;
  // Search, not the newest-100 window: the tracking issue may be older than 100 open issues.
  const issueSearch = `in:title ${JSON.stringify(failureTitle)} sort:created-asc`;
  const issueQuery = `[.[] | select(.title == ${JSON.stringify(failureTitle)})] | .[0].number // ""`;
  return `# Generated by scripts/codegen.ts. Edit scripts/build-${policy.name}-workflow.ts instead.
name: ${JSON.stringify(policy.name)}
on:
  schedule:
    - cron: '${policy.cron}'
  workflow_dispatch:
concurrency:
  group: ${policy.name}
  cancel-in-progress: false
permissions:
  actions: write
  contents: write
  issues: write
  pull-requests: write
jobs:
  bump:
    if: github.ref == 'refs/heads/main'
    runs-on: ubuntu-24.04
    timeout-minutes: 15
    steps:
      - uses: ${RUNTIME_BUNDLE_ACTION_PINS.checkout} # v7.0.1
        with:
          fetch-depth: 0
          persist-credentials: false
      - uses: ${RUNTIME_BUNDLE_ACTION_PINS.setupBun}
        with:
          bun-version-file: .bun-version
      - run: bun install --frozen-lockfile
      - name: ${JSON.stringify(policy.proposal.name)}
        env:
          GH_TOKEN: \${{ github.token }}
        run: |
          set -euo pipefail
          BRANCH=${shellQuote(policy.branch)}
          git config user.name "github-actions[bot]"
          git config user.email "github-actions[bot]@users.noreply.github.com"
          gh auth setup-git
          git fetch origin main:refs/remotes/origin/main
          BRANCH_EXISTS=false
          if git ls-remote --exit-code --heads origin "$BRANCH" >/dev/null 2>&1; then
            BRANCH_EXISTS=true
            git fetch origin "$BRANCH:refs/remotes/origin/$BRANCH"
            git checkout -B "$BRANCH" "origin/$BRANCH"
            git merge --no-edit origin/main
          else
            git checkout -b "$BRANCH"
          fi
${indentScript(policy.proposal.prepare)}
          if [ -z "$(git status --porcelain=v1 --untracked-files=all -- ${paths})" ] && git diff --quiet origin/main...HEAD -- ${paths}; then
            exit 0
          fi
${indentScript(policy.proposal.checkAndReport)}
          if [ -n "$(git status --porcelain=v1 --untracked-files=all -- ${paths})" ]; then
            git add -- ${paths}
            git commit -m "$TITLE" --only -- ${paths}
          fi
          git push origin "HEAD:$BRANCH"
          PR_NUMBER="$(gh pr list --state open --head "$BRANCH" --json number --jq '.[].number')"
          REPORT_START=${shellQuote(REPORT_START)}
          REPORT_END=${shellQuote(REPORT_END)}
          REPORT="$(cat "$BODY_FILE")"
          printf -v REPORT_SECTION '%s\\n%s\\n%s' "$REPORT_START" "$REPORT" "$REPORT_END"
          PR_BODY_FILE="$RUNNER_TEMP/maintenance-pr-body.md"
          if [ -z "$PR_NUMBER" ]; then
            printf '%s\\n' "$REPORT_SECTION" > "$PR_BODY_FILE"
            gh pr create --base main --head "$BRANCH" --title "$TITLE" --body-file "$PR_BODY_FILE"
          else
            # The PR body is untrusted data: keep it in variables and files only.
            # A marker counts only at the start of a line, so prose that quotes one is left alone.
            NL=$'\\n'
            CURRENT_BODY="$NL$(gh pr view "$PR_NUMBER" --json body --jq '.body')"
            case "$CURRENT_BODY" in
              *"$NL$REPORT_START"*"$NL$REPORT_END"*)
                AFTER_START="\${CURRENT_BODY#*"$NL$REPORT_START"}"
                MERGED_BODY="\${CURRENT_BODY%%"$NL$REPORT_START"*}$NL$REPORT_SECTION\${AFTER_START#*"$NL$REPORT_END"}"
                printf '%s\\n' "\${MERGED_BODY#"$NL"}" > "$PR_BODY_FILE" ;;
              *) printf '%s\\n' "$REPORT_SECTION" > "$PR_BODY_FILE" ;;
            esac
            gh pr edit "$BRANCH" --title "$TITLE" --body-file "$PR_BODY_FILE"
          fi
          gh workflow run ci.yml --ref "$BRANCH"
  report-failure:
    needs: [bump]
    if: \${{ failure() }}
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    env:
      GH_TOKEN: \${{ github.token }}
      GH_REPO: \${{ github.repository }}
      RUN_URL: \${{ github.server_url }}/\${{ github.repository }}/actions/runs/\${{ github.run_id }}
    steps:
      - name: Report automation failure
        run: |
          set -euo pipefail
          TITLE=${shellQuote(failureTitle)}
          BODY="Workflow run failed: $RUN_URL"
          ISSUE_NUMBER="$(gh issue list --state open --search ${shellQuote(issueSearch)} --limit 100 --json number,title --jq ${shellQuote(issueQuery)})"
          if [ -n "$ISSUE_NUMBER" ]; then
            gh issue comment "$ISSUE_NUMBER" --body "$BODY"
          else
            gh issue create --title "$TITLE" --body "$BODY"
          fi
`;
};
