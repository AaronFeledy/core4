import { resolve } from "node:path";
import * as Schema from "effect/Schema";
import { formatGeneratedPaths } from "./_codegen-output.ts";
import { renderCiWorkflow } from "./build-ci-workflow.ts";

const ciWorkflow = Schema.Struct({
  name: Schema.String,
  jobs: Schema.Record(
    Schema.String,
    Schema.Struct({
      name: Schema.optionalKey(Schema.String),
      steps: Schema.optionalKey(
        Schema.Array(
          Schema.Struct({ name: Schema.optionalKey(Schema.String), run: Schema.optionalKey(Schema.String) }),
        ),
      ),
    }),
  ),
});

export const renderCiRerunWorkflow = (): string => {
  const { name, jobs } = Schema.decodeUnknownSync(ciWorkflow)(Bun.YAML.parse(renderCiWorkflow()));
  // REST uses the job's display name, falling back to its id. Also keep the
  // validator step name so a failure during gate setup cannot qualify.
  const summaryValidators = Object.fromEntries(
    Object.entries(jobs).flatMap(([id, job]) => {
      const validator = job.steps?.find((step) => step.run === "bun run scripts/validate-ci.ts");
      return validator?.name === undefined ? [] : [[job.name ?? id, validator.name]];
    }),
  );

  return `# Generated by scripts/codegen.ts — do not hand-edit. Edit scripts/build-ci-rerun-workflow.ts instead.
name: ci-rerun

on:
  workflow_run:
    workflows: [${name}]
    types: [completed]

permissions: {}

jobs:
  rerun-abandoned:
    if: \${{ github.event.workflow_run.conclusion == 'failure' && github.event.workflow_run.run_attempt == 1 }}
    concurrency: ci-rerun-\${{ github.event.workflow_run.id }}
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    permissions:
      actions: write
    steps:
      - name: Rerun failed jobs after runner loss
        shell: bash
        env:
          GH_REPO: \${{ github.repository }}
          GH_TOKEN: \${{ github.token }}
          RUN_ID: \${{ github.event.workflow_run.id }}
          CI_SUMMARY_VALIDATORS: '${JSON.stringify(summaryValidators).replaceAll("'", "''")}'
        run: |
          set -euo pipefail
          run="repos/$GH_REPO/actions/runs/$RUN_ID"
          reason=$(gh api --paginate "$run/attempts/1/jobs?per_page=100" |
            jq -rs --argjson validators "$CI_SUMMARY_VALIDATORS" '
              def abandoned: .conclusion == "cancelled" and .steps == [];
              def derived:
                $validators[.name] as $validator
                | .conclusion == "failure" and $validator != null
                  and ([.steps[] | select(.conclusion != "success" and .conclusion != "skipped")
                        | [.name, .conclusion]] == [[$validator, "failure"]]);
              [.[] | .jobs[]] as $jobs
              | if any($jobs[]; abandoned) | not then "no job was abandoned before its first step"
                elif any($jobs[]; .conclusion != "success" and .conclusion != "skipped"
                                  and (abandoned or derived | not)) then "another job failed independently"
                else "" end')
          if [[ -n "$reason" ]]; then
            echo "Skipping CI rerun: $reason."
            exit 0
          fi

          # The completion event may be stale if a rerun has already started.
          attempt=$(gh api "$run" --jq 'select(.path == ".github/workflows/ci.yml") | .run_attempt')
          if [[ "$attempt" != 1 ]]; then
            echo "Skipping CI rerun: the run is not attempt 1 of ci.yml."
            exit 0
          fi

          gh run rerun "$RUN_ID" --failed
`;
};

if (import.meta.main) {
  const output = resolve(import.meta.dirname, "../.github/workflows/ci-rerun.yml");
  await Bun.write(output, renderCiRerunWorkflow());
  await formatGeneratedPaths([output, import.meta.path]);
  console.log(`[build-ci-rerun-workflow] wrote ${output}`);
}
