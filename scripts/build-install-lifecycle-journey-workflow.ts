#!/usr/bin/env bun
import { resolve } from "node:path";
import { formatGeneratedPaths } from "./_codegen-output.ts";
import { CONTAINER_HELPER_JOB_ID, renderContainerHelperJob } from "./_container-helper-workflow.ts";
import { createJourneyWorkflowBuilder } from "./_journey-workflow.ts";
import { landoRootlessPrereqSteps } from "./build-ci-workflow.ts";
import { PLATFORM_READINESS_CELLS } from "./ci-platforms.ts";

const TRUSTED_EVIDENCE =
  "github.ref == 'refs/heads/main' && (github.event_name == 'schedule' || github.event_name == 'workflow_dispatch')";
const builder = createJourneyWorkflowBuilder("install-lifecycle");

const renderJob = (id: "linux-x64" | "windows-x64"): string => {
  const platform = builder.ciPlatformFor(id);
  const cell = PLATFORM_READINESS_CELLS.find((candidate) => candidate.id === id);
  if (!cell) throw new Error(`Missing lifecycle runner: ${id}`);
  return `  install-lifecycle-${id}:
    if: ${TRUSTED_EVIDENCE}
    needs: [${CONTAINER_HELPER_JOB_ID}]
    runs-on: ${builder.renderRunsOn(id === "linux-x64" ? "ubuntu-24.04" : cell.runsOn)}
    timeout-minutes: 90
    env:
      LANDO_LIFECYCLE_FRESH_RUNNER: "1"
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
        with:
          persist-credentials: false

${builder.isolateRootsStep}

${builder.setupBunSteps}

${builder.derivedSourcesSteps}

${builder.renderCompileStep(platform)}

${id === "linux-x64" ? landoRootlessPrereqSteps : ""}

      - name: Install, setup, serve HTTP, destroy, uninstall
        run: bun run scripts/install-lifecycle-journey.ts --binary "dist/${platform.binaryName}" --work-dir "\${{ runner.temp }}/install-lifecycle-\${{ github.run_id }}-\${{ github.run_attempt }}" --report "\${{ runner.temp }}/install-lifecycle.json"

      - name: Upload lifecycle evidence
        if: always()
        uses: actions/upload-artifact@v6
        with:
          name: install-lifecycle-${id}
          path: \${{ runner.temp }}/install-lifecycle.json
          if-no-files-found: error
          retention-days: 14
`;
};

export const renderInstallLifecycleWorkflow =
  (): string => `# Generated by scripts/build-install-lifecycle-journey-workflow.ts; do not hand-edit.
name: install-lifecycle

on:
  schedule:
    - cron: '30 6 * * *'
  workflow_dispatch:

permissions:
  contents: read

defaults:
  run:
    shell: bash

concurrency:
  group: install-lifecycle-evidence
  cancel-in-progress: false

jobs:
${renderContainerHelperJob().replace(/ {4}runs-on: .+/u, `    if: ${TRUSTED_EVIDENCE}\n    runs-on: ubuntu-24.04`)}

${(["linux-x64", "windows-x64"] as const).map(renderJob).join("\n")}`;

if (import.meta.main) {
  const output = resolve(import.meta.dirname, "../.github/workflows/install-lifecycle.yml");
  await Bun.write(output, renderInstallLifecycleWorkflow());
  await formatGeneratedPaths([output, import.meta.path]);
}
