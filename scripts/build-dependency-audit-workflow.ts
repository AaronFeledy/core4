#!/usr/bin/env bun
import { resolve } from "node:path";
import { formatGeneratedPaths } from "./_codegen-output.ts";
import { RUNTIME_BUNDLE_ACTION_PINS } from "./runtime-bundle-supply-chain.ts";

export const renderDependencyAuditWorkflow =
  (): string => `# Generated by scripts/build-dependency-audit-workflow.ts. Do not edit.
name: dependency-audit
on:
  schedule:
    - cron: '23 5 * * *'
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: dependency-audit
  cancel-in-progress: false
jobs:
  report:
    if: github.ref == format('refs/heads/{0}', github.event.repository.default_branch) && (github.event_name == 'schedule' || github.event_name == 'workflow_dispatch')
    runs-on: ubuntu-26.04
    timeout-minutes: 10
    permissions:
      contents: read
      issues: write
    steps:
      - uses: ${RUNTIME_BUNDLE_ACTION_PINS.checkout} # v7.0.1
        with:
          persist-credentials: false
      - uses: ${RUNTIME_BUNDLE_ACTION_PINS.setupBun}
        with:
          bun-version-file: .bun-version
      - run: bun install --frozen-lockfile --ignore-scripts
      - name: Reconcile dependency audit issue
        env:
          GH_TOKEN: \${{ github.token }}
          GH_REPO: \${{ github.repository }}
        run: bun run scripts/dependency-audit.ts
`;

if (import.meta.main) {
  const output = resolve(import.meta.dirname, "../.github/workflows/dependency-audit.yml");
  await Bun.write(output, renderDependencyAuditWorkflow());
  // Biome 1.x does not process YAML; include the renderer source in the shared check.
  await formatGeneratedPaths([output, import.meta.path]);
}
