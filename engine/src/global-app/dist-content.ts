import { mapFailures } from "@lando/sdk/command-result";
import { sha256Hex } from "@lando/sdk/digest";
import { GlobalAppError, GlobalDistConflictError } from "@lando/sdk/errors";
import { emitLandofileYaml } from "@lando/sdk/landofile";
import { type AbsolutePath, type MountInput, ServiceConfig } from "@lando/sdk/schema";
import type { FileSystem } from "@lando/sdk/services";
import { type Context, Effect, Schema } from "effect";

const distMarker = "# DO NOT EDIT — regenerated by Lando.";
const distOverrideHint = "# Put global app overrides in .lando.yml (merged after this file).";
const distHashPrefix = "# lando-global-dist-sha256: ";

const encodeServices = Schema.encodeSync(Schema.Record(Schema.String, ServiceConfig));

export const renderGlobalDist = (services: Readonly<Record<string, ServiceConfig>>): string => {
  const body = emitLandofileYaml(
    { name: "global", runtime: 4, services: encodeServices(services) },
    { sortKeys: true },
  );
  return [distMarker, distOverrideHint, `${distHashPrefix}${sha256Hex(body)}`, body].join("\n");
};

// Windows drive-letter prefix ("C:\\" or "C:/") whose ":" is a path char, not a mount separator.
const DRIVE_LETTER_PREFIX = /^[A-Za-z]:[\\/]/;

const isBindPathSource = (source: string): boolean =>
  source.startsWith(".") ||
  source.startsWith("/") ||
  source.startsWith("~") ||
  DRIVE_LETTER_PREFIX.test(source);

const stringMountBindSource = (entry: string): string | undefined => {
  const source = DRIVE_LETTER_PREFIX.test(entry)
    ? `${entry.slice(0, 2)}${entry.slice(2).split(":")[0] ?? ""}`
    : entry.split(":")[0];
  if (source === undefined || source.length === 0) return undefined;
  return isBindPathSource(source) ? source : undefined;
};

const mountBindSource = (mount: MountInput): string | undefined => {
  if (typeof mount === "string") return stringMountBindSource(mount);
  return (mount.type ?? "bind") === "bind" && mount.source !== undefined ? mount.source : undefined;
};

export const bindMountSources = (services: Readonly<Record<string, ServiceConfig>>): ReadonlyArray<string> =>
  Object.values(services).flatMap((service) =>
    (service.mounts ?? []).flatMap((mount) => {
      const source = mountBindSource(mount);
      return source === undefined ? [] : [source];
    }),
  );

const splitYamlLines = (content: string): ReadonlyArray<string> => content.split(/\r?\n/);

const currentDistBody = (content: string): string => splitYamlLines(content).slice(3).join("\n");

const embeddedDistHash = (content: string): string | undefined =>
  splitYamlLines(content)
    .find((line) => line.startsWith(distHashPrefix))
    ?.slice(distHashPrefix.length)
    .trim();

export const readManagedGlobalDist = Effect.fn("GlobalAppService.readManagedDist")(function* (
  fileSystem: Context.Service.Shape<typeof FileSystem>,
  path: AbsolutePath,
) {
  const content = yield* fileSystem.readText(path).pipe(
    mapFailures(
      (cause) =>
        new GlobalAppError({
          operation: "regenerateDist",
          message: `Unable to read the generated global app Landofile at ${path}.`,
          cause,
          remediation: `Ensure ${path} is readable, then retry \`lando global:reconcile\`.`,
        }),
    ),
  );
  if (splitYamlLines(content)[0] !== distMarker) {
    return yield* Effect.fail(
      new GlobalDistConflictError({
        message: `The generated global app Landofile path is not managed by Lando: ${path}.`,
        path,
        reason: "foreign-file",
        remediation: "Move .lando.dist.yml aside or move overrides into .lando.yml, then rerun.",
      }),
    );
  }
  const currentHash = embeddedDistHash(content);
  const actualHash = sha256Hex(currentDistBody(content));
  if (currentHash !== actualHash) {
    return yield* Effect.fail(
      new GlobalDistConflictError({
        message: `The generated global app Landofile was manually edited: ${path}.`,
        path,
        reason: "manual-edit",
        remediation:
          "move changes from .lando.dist.yml into .lando.yml, then restore the generated file and rerun.",
      }),
    );
  }
  return content;
});
