import { Schema } from "effect";

import { defineTransitions } from "../transitions/index.ts";

import { NetworkConfig } from "./config.ts";
import { FileSyncMode as FileSyncModeSchema } from "./file-sync.ts";
import { AppRef } from "./networking.ts";
import { AbsoluteContainerPath, AbsolutePath, PortablePath, ServiceName } from "./primitives.ts";

// FileSyncEngine - pluggable file-sync engine contract.

/**
 * Opaque, engine-issued handle to a created file-sync session. Stable
 * across pause/resume cycles. Engines own the encoding; the planner
 * never inspects the contents.
 */
export const FileSyncSessionRef = Schema.String.pipe(Schema.brand("FileSyncSessionRef"));
export type FileSyncSessionRef = typeof FileSyncSessionRef.Type;

/**
 * Engine capability matrix declared at registration time. Used by
 * `AppPlanner` to verify a `MountPlan`'s requested `mode` is supported
 * before a session is created.
 */
export const FileSyncEngineCapabilities = Schema.Struct({
  /** Supported sync modes; at least one MUST be declared. */
  modes: Schema.Array(FileSyncModeSchema).pipe(Schema.check(Schema.isMinLength(1))),
  /**
   * `auto`: engine deploys its in-container agent on first session start
   * via `RuntimeProvider.run`. `preinstalled`: engine assumes the agent
   * binary is already present in the target image. `none`: engine does
   * not require a per-target agent (passthrough / no-op engines).
   */
  remoteAgentDeployment: Schema.Literals(["auto", "preinstalled", "none"]),
  /** True iff the engine honors `FileSyncSessionSpec.excludes`. */
  exclusionPatterns: Schema.Boolean,
  /** True iff the engine emits drift / conflict events. */
  conflictReporting: Schema.Boolean,
  /** True iff the engine emits progress events for the four standard phases. */
  progressReporting: Schema.Boolean,
});
export type FileSyncEngineCapabilities = Schema.Schema.Type<typeof FileSyncEngineCapabilities>;

/**
 * Setup options for `FileSyncEngine.setup`. Mirrors the
 * `ProviderSetupOptions` shape so `lando setup` can pass through the same
 * `--force` flag.
 */
export const FileSyncSetupOptions = Schema.Struct({
  /** Re-run setup even if the engine reports `isAvailable: true`. */
  force: Schema.Boolean,
  network: Schema.optionalKey(NetworkConfig),
});
export type FileSyncSetupOptions = Schema.Schema.Type<typeof FileSyncSetupOptions>;

/**
 * Target the engine should sync into. `volume` is a provider-owned named
 * volume; `service` is a path inside another service container.
 */
export const FileSyncSessionTarget = Schema.Union([
  Schema.TaggedStruct("volume", {
    /** Provider-owned volume name. */
    name: Schema.String,
    /** Container-side mount path. */
    path: PortablePath,
  }),
  Schema.TaggedStruct("service", {
    /** Target service name. */
    service: ServiceName,
    /** Container-side path inside the target service. */
    path: PortablePath,
  }),
]);
export type FileSyncSessionTarget = Schema.Schema.Type<typeof FileSyncSessionTarget>;

/**
 * Per-mount session creation spec. Generated by `AppPlanner` from
 * accelerated `MountPlan` entries.
 */
export const FileSyncSessionSpec = Schema.Struct({
  /** Owning app reference. */
  app: AppRef,
  /** Service whose mount this session backs. */
  service: ServiceName,
  /** Stable mount key inside the owning service. */
  mountKey: Schema.String,
  /** Host-side source root (after symlink resolution). */
  source: AbsolutePath,
  /** Where the synced bytes should appear. */
  target: FileSyncSessionTarget,
  /** Requested sync mode; engines MAY upgrade per `FileSyncDriftError.suggestedMode`. */
  mode: FileSyncModeSchema,
  /** Engine-honored exclude patterns from the service config. */
  excludes: Schema.Array(Schema.String),
  /** Optional ownership / mode overrides applied on the target side. */
  permissions: Schema.optionalKey(
    Schema.Struct({
      owner: Schema.optionalKey(Schema.String),
      mode: Schema.optionalKey(Schema.String),
    }),
  ),
});
export type FileSyncSessionSpec = Schema.Schema.Type<typeof FileSyncSessionSpec>;

/** Existing owned sync volumes proved by retained-target writer quiescence. */
export const RetainedFileSyncQuiescence = Schema.Struct({
  preparedVolumeNames: Schema.Array(Schema.String),
});
export type RetainedFileSyncQuiescence = Schema.Schema.Type<typeof RetainedFileSyncQuiescence>;

/**
 * Provider-owned, verified container endpoint for one planned sync session.
 * The endpoint is data only; its cleanup action stays with the provider.
 */
export const PreparedFileSyncTarget = Schema.Struct({
  session: FileSyncSessionSpec.annotate({
    description: "Exact planned file-sync session backed by this prepared target.",
  }),
  endpoint: Schema.TaggedStruct("container", {
    containerId: Schema.String.pipe(Schema.check(Schema.isMinLength(1))).annotate({
      description: "Verified running helper container ID, never a mutable name.",
    }),
    path: AbsoluteContainerPath.annotate({
      description: "Absolute path mounted inside the verified helper container.",
    }),
    volumeName: Schema.String.pipe(Schema.check(Schema.isMinLength(1))).annotate({
      description: "Owned named volume backing the planned session target.",
    }),
    permissions: Schema.optionalKey(
      Schema.Struct({
        owner: Schema.String,
        group: Schema.String,
        defaultFileMode: Schema.String,
        defaultDirectoryMode: Schema.String,
      }),
    ),
  }).annotate({
    description: "Provider-verified container endpoint for the session.",
  }),
});
export type PreparedFileSyncTarget = Schema.Schema.Type<typeof PreparedFileSyncTarget>;

/** Lifecycle status surfaced by `FileSyncEngine.listSessions`. */
export const FileSyncSessionStatus = Schema.Literals(["running", "paused", "draining", "errored"]);
export type FileSyncSessionStatus = typeof FileSyncSessionStatus.Type;

/**
 * Diagnostic snapshot of a single running session.
 */
export const FileSyncSessionInfo = Schema.Struct({
  ref: FileSyncSessionRef,
  app: AppRef,
  service: ServiceName,
  mountKey: Schema.String,
  /** Full applied spec, used to verify session reuse before mounting synced bytes. */
  spec: FileSyncSessionSpec,
  status: FileSyncSessionStatus,
  lastUpdatedAt: Schema.DateTimeUtcFromString,
  /** Optional structured detail (drift count, last error message, etc.). */
  detail: Schema.optionalKey(Schema.String),
  /** Validated relative paths for an observed synchronization conflict. */
  conflictedPaths: Schema.optionalKey(Schema.Array(Schema.String)).annotate({
    description: "Validated relative paths for an observed synchronization conflict.",
  }),
});
export type FileSyncSessionInfo = Schema.Schema.Type<typeof FileSyncSessionInfo>;

/** Filter for `FileSyncEngine.listSessions`; absent fields match everything. */
export const FileSyncSessionFilter = Schema.Struct({
  app: Schema.optionalKey(AppRef),
  service: Schema.optionalKey(ServiceName),
  mountKey: Schema.optionalKey(Schema.String),
});
export type FileSyncSessionFilter = Schema.Schema.Type<typeof FileSyncSessionFilter>;

/**
 * One chunk in the `FileSyncEngine.streamEvents` stream. Engines MUST
 * emit `progress` chunks for at least the four standard phases when
 * `progressReporting: true`, and `conflict` chunks when
 * `conflictReporting: true`. `info` is a free-form diagnostic chunk for
 * the active `Logger`.
 */
export const FileSyncEventChunk = Schema.Union([
  Schema.TaggedStruct("progress", {
    sessionRef: FileSyncSessionRef,
    phase: Schema.Literals(["initial-scan", "staging", "transitioning", "watching"]),
    /** 0..1 inclusive when known; otherwise omit. */
    completed: Schema.optionalKey(
      Schema.Number.pipe(Schema.check(Schema.isBetween({ minimum: 0, maximum: 1 }))),
    ),
    message: Schema.optionalKey(Schema.String),
  }),
  Schema.TaggedStruct("conflict", {
    sessionRef: FileSyncSessionRef,
    conflictedPaths: Schema.Array(Schema.String),
  }),
  Schema.TaggedStruct("info", {
    sessionRef: FileSyncSessionRef,
    message: Schema.String,
  }),
]);
export type FileSyncEventChunk = Schema.Schema.Type<typeof FileSyncEventChunk>;

// ====================================================================
// App disposal lifecycle
// ====================================================================

/**
 * Where an app stands in a durable file-sync engine's disposal lifecycle, as
 * reported by `FileSyncEngine.appLifecycle.disposalPhase`.
 *
 * - `absent`: the engine holds no sessions and no disposal receipt.
 * - `active`: sessions exist and may sync (a drain is not settled).
 * - `drained`: every session is flushed and paused; the app is restartable.
 * - `disposing`: disposal began and may be resumed; the drained state is gone.
 * - `completed`: sessions and provider targets are gone; the completion receipt
 *   survives retries until creating a session for the app clears it.
 */
export const FileSyncDisposalPhase = Schema.Literals([
  "absent",
  "active",
  "drained",
  "disposing",
  "completed",
]);
export type FileSyncDisposalPhase = typeof FileSyncDisposalPhase.Type;

/**
 * The one declared edge table for the app disposal lifecycle. Keys are the
 * `appLifecycle` operations plus `createSession`, the only other operation that
 * moves the phase. `settledIn` lists phases with nothing left for the operation
 * to do. An engine may keep a finer private ledger, but its projection onto
 * these phases must agree with every edge here.
 */
export const fileSyncDisposalTransitions = defineTransitions<FileSyncDisposalPhase>()({
  createSession: { from: ["absent", "active", "completed"], to: "active" },
  invalidateDrain: { from: ["active", "drained"], to: "active", settledIn: ["absent", "completed"] },
  drain: { from: ["active", "drained"], to: "drained" },
  dispose: { from: ["drained", "disposing"], to: "disposing" },
  completeDisposal: { from: ["disposing"], to: "completed", settledIn: ["completed"] },
});
export type FileSyncDisposalOperation = keyof typeof fileSyncDisposalTransitions.edges;

/** The lifecycle operations an orchestrator runs, in order, to retire an app's sessions. */
export type FileSyncDisposalStep = Extract<
  FileSyncDisposalOperation,
  "drain" | "dispose" | "completeDisposal"
>;

const DISPOSAL_STEPS: ReadonlyArray<FileSyncDisposalStep> = ["drain", "dispose", "completeDisposal"];

/**
 * Operations still owed to reach `completed` from `phase`, in execution order.
 * Resume semantics fall out of the table: a step the phase has already passed
 * is not planned, and a step whose edge re-accepts the phase (`drain` from
 * `drained`, `dispose` from `disposing`) is re-run. `absent` and `completed`
 * owe nothing. Provider target cleanup must succeed before `completeDisposal`.
 */
export const planFileSyncDisposal = (phase: FileSyncDisposalPhase): ReadonlyArray<FileSyncDisposalStep> => {
  const planned: Array<FileSyncDisposalStep> = [];
  let current = phase;
  for (const operation of DISPOSAL_STEPS) {
    const verdict = fileSyncDisposalTransitions.step(operation, current);
    switch (verdict._tag) {
      case "Advance":
        planned.push(operation);
        current = verdict.to;
        break;
      case "Settled":
      case "Illegal":
        break;
      default: {
        const exhaustive: never = verdict;
        return exhaustive;
      }
    }
  }
  return planned;
};

/**
 * True once disposal can no longer be abandoned for a restart: the engine is
 * `disposing` or `completed`. Derived from the table, as the phases that are
 * neither `absent` nor open to `drain`.
 */
export const fileSyncDisposalCommitted = (phase: FileSyncDisposalPhase): boolean =>
  phase !== "absent" && fileSyncDisposalTransitions.step("drain", phase)._tag !== "Advance";

/**
 * Whether a start must call `invalidateDrain`. An app that owns sessions always
 * invalidates; otherwise only a phase the table does not settle does, so a
 * bare `absent` or `completed` app is left alone.
 */
export const fileSyncInvalidationRequired = (phase: FileSyncDisposalPhase, ownsSessions: boolean): boolean =>
  ownsSessions || fileSyncDisposalTransitions.step("invalidateDrain", phase)._tag !== "Settled";
