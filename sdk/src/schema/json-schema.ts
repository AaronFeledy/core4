const titleFromSchemaName = (schemaName: string): string =>
  schemaName.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2");

const BUILT_IN_DESCRIPTIONS = new Set([
  "a string",
  "a number",
  "a boolean",
  "a bigint",
  "a symbol",
  "an object in the TypeScript meaning, i.e. the `object` type",
]);

const DESCRIPTION_OVERRIDES: Readonly<Partial<Record<string, string>>> = {
  ...PUBLIC_SCHEMA_DESCRIPTIONS,
  ...CATALOG_SERVICE_SCHEMA_DESCRIPTIONS,
};

const schemaDescription = (schemaName: string, ast: AST.AST): string => {
  const own = AST.resolveDescription(ast);
  return own !== undefined && !BUILT_IN_DESCRIPTIONS.has(own)
    ? own
    : (DESCRIPTION_OVERRIDES[schemaName] ??
        `Public Lando schema contract for ${titleFromSchemaName(schemaName)}.`);
};

const annotatedCatalogSchema = <Name extends keyof typeof catalogServiceSchemaRegistry>(
  schemaName: Name,
  schema: (typeof catalogServiceSchemaRegistry)[Name],
): (typeof catalogServiceSchemaRegistry)[Name] =>
  schema.annotate({
    identifier: AST.resolveIdentifier(schema.ast) ?? schemaName,
    title: AST.resolveTitle(schema.ast) ?? titleFromSchemaName(schemaName),
    description: AST.resolveDescription(schema.ast) ?? CATALOG_SERVICE_SCHEMA_DESCRIPTIONS[schemaName],
  }) as (typeof catalogServiceSchemaRegistry)[Name];

const annotatedPublicSchema = <Name extends keyof typeof rawPublicSchemaRegistry>(
  schemaName: Name,
  schema: (typeof rawPublicSchemaRegistry)[Name],
): (typeof rawPublicSchemaRegistry)[Name] =>
  schema.annotate({
    identifier: AST.resolveIdentifier(schema.ast) ?? schemaName,
    title: AST.resolveTitle(schema.ast) ?? titleFromSchemaName(schemaName),
    description: schemaDescription(schemaName, schema.ast),
  }) as (typeof rawPublicSchemaRegistry)[Name];

