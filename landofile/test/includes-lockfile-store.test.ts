import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { Effect } from "effect";

import type { LandofileShape } from "@lando/sdk/schema";
import type { StateStoreShape } from "@lando/sdk/services";
import { makeStateStore } from "@lando/state-store/service";

import type { GitIncludeCloner } from "../src/includes.ts";
import {
  resolveAuthoredIncludes,
  updateAuthoredIncludes as updateLandofileIncludes,
  verifyAuthoredIncludes as verifyLandofileIncludes,
} from "./include-pipeline.ts";
import { makeTestLandofilePorts, makeTestLandofileStateStore } from "./support.ts";

const sha256 = (content: string): string => new Bun.CryptoHasher("sha256").update(content).digest("hex");

const renderExpectedLockfile = (
  entries: ReadonlyArray<{ source: string; resolved: string; checksum: string }>,
): string => {
  const escapeScalar = (value: string): string => {
    if (/^[A-Za-z0-9._~:/@+-]+$/u.test(value) && value !== "true" && value !== "false" && value !== "null")
      return value;
    return `'${value.replace(/'/gu, "''")}'`;
  };
  const lines = ["# DO NOT EDIT - generated by Lando.", "includes:"];
  const sorted = [...entries].sort((l, r) => (l.source < r.source ? -1 : l.source > r.source ? 1 : 0));
  for (const entry of sorted) {
    lines.push(`  - source: ${escapeScalar(entry.source)}`);
    lines.push(`    resolved: ${escapeScalar(entry.resolved)}`);
    lines.push(`    checksum: ${entry.checksum}`);
  }
  lines.push("");
  return lines.join("\n");
};

const FRAGMENT = "services:\n  database:\n    type: postgres\n";

const makeRecordingStore = (onOpen: () => void): StateStoreShape => {
  const store = makeStateStore({
    privateFileAccess: {
      enforce: async () => undefined,
      verify: async () => undefined,
    },
  });
  return {
    withLock: store.withLock,
    open: (spec) => {
      onOpen();
      return store.open(spec);
    },
  };
};

const clonerReturning = (commitSha: string): GitIncludeCloner => ({
  clone: async ({ dest }) => {
    await mkdir(dest, { recursive: true });
    await writeFile(join(dest, "postgres.yml"), FRAGMENT, "utf8");
    return { commitSha };
  },
});

describe("store-backed include lockfile", () => {
  let appRoot: string;
  let cacheRoot: string;
  let stateStore: StateStoreShape;
  let previousCacheRoot: string | undefined;

  beforeEach(async () => {
    appRoot = await mkdtemp(join(tmpdir(), "lando-includes-store-app-"));
    cacheRoot = await mkdtemp(join(tmpdir(), "lando-includes-store-cache-"));
    previousCacheRoot = process.env.LANDO_USER_CACHE_ROOT;
    process.env.LANDO_USER_CACHE_ROOT = cacheRoot;
    stateStore = makeTestLandofileStateStore();
  });

  afterEach(async () => {
    process.env.LANDO_USER_CACHE_ROOT = previousCacheRoot;
    await rm(appRoot, { recursive: true, force: true });
    await rm(cacheRoot, { recursive: true, force: true });
  });

  const landofile = (): LandofileShape =>
    ({ includes: [{ source: "github:acme/fragments", path: "postgres.yml" }] }) as LandofileShape;

  test("update writes the lockfile byte-for-byte through the store", async () => {
    const lockPath = join(appRoot, ".lando.lock.yml");
    let opens = 0;
    const stateStore = makeRecordingStore(() => {
      opens += 1;
    });
    const report = await Effect.runPromise(
      updateLandofileIncludes({
        landofile: landofile(),
        appRoot,
        cacheRoot,
        ports: makeTestLandofilePorts(cacheRoot),
        stateStore,
        deps: { gitCloner: clonerReturning("a".repeat(40)) },
      }),
    );
    expect(report.wrote).toBe(true);
    expect(opens).toBe(3);
    const written = await readFile(lockPath, "utf8");
    const expected = renderExpectedLockfile([
      { source: "github:acme/fragments/postgres.yml", resolved: "a".repeat(40), checksum: sha256(FRAGMENT) },
    ]);
    expect(written).toBe(expected);
  });

  test("verify reads the store-backed lockfile and confirms a matching entry", async () => {
    const lockPath = join(appRoot, ".lando.lock.yml");
    await Effect.runPromise(
      updateLandofileIncludes({
        landofile: landofile(),
        appRoot,
        cacheRoot,
        ports: makeTestLandofilePorts(cacheRoot),
        stateStore,
        deps: { gitCloner: clonerReturning("a".repeat(40)) },
      }),
    );
    const onDisk = await readFile(lockPath, "utf8");
    const report = await Effect.runPromise(
      verifyLandofileIncludes({
        landofile: landofile(),
        appRoot,
        cacheRoot,
        ports: makeTestLandofilePorts(cacheRoot),
        stateStore,
        deps: { gitCloner: clonerReturning("a".repeat(40)) },
      }),
    );
    expect(report.ok).toBe(true);
    // Verify is read-only: the store-backed read must not rewrite the file.
    expect(await readFile(lockPath, "utf8")).toBe(onDisk);
  });

  test("verify reads a block-style lockfile fixture without rewriting it", async () => {
    const lockPath = join(appRoot, ".lando.lock.yml");
    const fixture = renderExpectedLockfile([
      { source: "github:acme/fragments/postgres.yml", resolved: "a".repeat(40), checksum: sha256(FRAGMENT) },
    ]);
    await writeFile(lockPath, fixture, "utf8");
    const report = await Effect.runPromise(
      verifyLandofileIncludes({
        landofile: landofile(),
        appRoot,
        cacheRoot,
        ports: makeTestLandofilePorts(cacheRoot),
        stateStore,
        deps: { gitCloner: clonerReturning("a".repeat(40)) },
      }),
    );
    expect(report.ok).toBe(true);
    expect(await readFile(lockPath, "utf8")).toBe(fixture);
  });

  test("a corrupt lockfile fails closed without rewriting or quarantine", async () => {
    const lockPath = join(appRoot, ".lando.lock.yml");
    const corrupt = "::: not valid lockfile yaml :::\n";
    await writeFile(lockPath, corrupt, "utf8");
    const report = await Effect.runPromise(
      verifyLandofileIncludes({
        landofile: landofile(),
        appRoot,
        cacheRoot,
        ports: makeTestLandofilePorts(cacheRoot),
        stateStore,
        deps: { gitCloner: clonerReturning("abc123") },
      }),
    );
    expect(report.ok).toBe(false);
    expect(report.failures).toMatchObject([
      {
        _tag: "LandofileParseError",
        filePath: lockPath,
        remediation:
          "Restore .lando.lock.yml from version control or remove it, then run lando app:includes:update.",
      },
    ]);
    expect((await readdir(appRoot)).some((name) => name.startsWith(".lando.lock.yml.corrupt-"))).toBe(false);
    expect(await readFile(lockPath, "utf8")).toBe(corrupt);
  });

  test("load preserves a parse error when the lockfile becomes corrupt before the locked write", async () => {
    // Given
    const lockPath = join(appRoot, ".lando.lock.yml");
    await writeFile(lockPath, "includes:\n", "utf8");
    const corruptingStore: StateStoreShape = {
      ...stateStore,
      withLock: (key, body) =>
        stateStore.withLock(
          key,
          Effect.promise(() => writeFile(lockPath, "::: corrupt lock :::\n", "utf8")).pipe(
            Effect.andThen(body),
          ),
        ),
    };
    // When
    const error = await Effect.runPromise(
      Effect.flip(
        resolveAuthoredIncludes({
          landofile: landofile(),
          appRoot,
          cacheRoot,
          ports: makeTestLandofilePorts(cacheRoot),
          stateStore: corruptingStore,
          deps: { gitCloner: clonerReturning("a".repeat(40)) },
        }),
      ),
    );
    // Then
    expect(error).toMatchObject({
      _tag: "LandofileParseError",
      filePath: lockPath,
      remediation:
        "Restore .lando.lock.yml from version control or remove it, then run lando app:includes:update.",
    });
  });
});
